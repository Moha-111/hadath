// Lists the licenses of runtime and build dependencies found in node_modules.
// Usage: npm run licenses  (writes THIRD_PARTY_LICENSES.md)
import fs from 'node:fs';
import path from 'node:path';

const root = JSON.parse(fs.readFileSync('package.json', 'utf8'));
const rows = [];
const seen = new Set();
function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    if (name.startsWith('.')) continue;
    const p = path.join(dir, name);
    if (name.startsWith('@')) { walk(p); continue; }
    const pkgFile = path.join(p, 'package.json');
    if (!fs.existsSync(pkgFile)) continue;
    const pkg = JSON.parse(fs.readFileSync(pkgFile, 'utf8'));
    const key = `${pkg.name}@${pkg.version}`;
    if (seen.has(key) || !pkg.name) continue;
    seen.add(key);
    const lic = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (pkg.licenses ?? []).map((l) => l.type).join(' OR ') ?? 'UNKNOWN';
    const kind = root.dependencies?.[pkg.name] ? 'runtime' : root.devDependencies?.[pkg.name] ? 'dev (direct)' : 'transitive';
    rows.push({ name: pkg.name, version: pkg.version, lic: lic || 'UNKNOWN', kind });
  }
}
walk('node_modules');
rows.sort((a, b) => (a.kind === b.kind ? a.name.localeCompare(b.name) : a.kind.localeCompare(b.kind)));
const counts = rows.reduce((m, r) => ((m[r.lic] = (m[r.lic] ?? 0) + 1), m), {});
let out = '# Third-party licenses\n\nGenerated by `npm run licenses` from installed packages. HADATH original code is Apache-2.0; each dependency below keeps its own license. Only `runtime` packages are shipped in the built app (React, React DOM, and the font packages).\n\n';
out += '## Summary\n\n' + Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `- ${l}: ${n}`).join('\n') + '\n\n';
out += '## Packages\n\n| Package | Version | License | Type |\n|---|---|---|---|\n' + rows.map((r) => `| ${r.name} | ${r.version} | ${r.lic} | ${r.kind} |`).join('\n') + '\n';
process.stdout.write(out);
